import Panel from './Panel.jsx'

export default function SensorReadings({ temperature, diameter, hasSamples, extruding }) {
  const readings = [
    { label: 'Hot-end temperature', value: temperature.toFixed(1), unit: '°C', detail: 'Simulated temperature sensor' },
    { label: 'Camera fiber diameter', value: diameter.toFixed(2), unit: 'mm', detail: !hasSamples ? 'Illustrative initial value' : extruding ? 'Simulated camera · sampling' : 'Last simulated sample · held' },
  ]
  return (
    <Panel id="sensors-title" eyebrow="Instrumentation" title="Simulated sensor readings" badge="Simulated">
      <div className="sensor-grid">
        {readings.map((sensor) => (
          <div className="sensor-card" key={sensor.label}>
            <p>{sensor.label}</p>
            <div className="sensor-value">{sensor.value}<span>{sensor.unit}</span></div>
            <span className="sensor-detail">{sensor.detail}</span>
          </div>
        ))}
      </div>
      <p className="help-text">Generated by artificial demo rules. No hardware, camera access, or real measurements.</p>
    </Panel>
  )
}
